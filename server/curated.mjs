const tagLabels = { hiphop: 'рэп', pop: 'поп', rock: 'рок', indie: 'инди', electronic: 'электроника', phonk: 'фонк', rnb: 'R&B', jazz: 'джаз', ambient: 'эмбиент', classical: 'классика', lofi: 'lo-fi', house: 'хаус', techno: 'техно' }
const clean = value => String(value || '').toLocaleLowerCase().normalize('NFKD').replace(/[^\p{L}\p{N}]+/gu, ' ').trim()

export const curatedArtists = raw.map(([id, name, tags, language], index) => ({
  id,
  name,
  tags,
  language,
  tint: palette[hash(name) % palette.length],
  description: tags.map(tag => tagLabels[tag] || tag).join(' · '),
  popularity: 100000 - index * 7,
}))

export const curatedById = new Map(curatedArtists.map(item => [item.id, item]))
export const curatedByName = new Map(curatedArtists.map(item => [clean(item.name), item]))

export function findCuratedByName(name) { return curatedByName.get(clean(name)) || null }
