export type CatalogEntry = { id: string; name: string; query: string; tags: string[]; tint: string; kind: 'artist' | 'mix' }
export type CatalogGroup = { id: string; label: string; subtitle: string; description: string; tint: string; entries: CatalogEntry[] }

const palette = ['#9b545d', '#607b6c', '#c49b5a', '#84736f', '#95705c', '#a0879b', '#bd9956', '#8277ac', '#b97684', '#778899', '#769c82', '#6f91a7', '#967f73', '#b58368', '#798e93', '#a3af4e']
let tintIndex = 0
const nextTint = () => palette[tintIndex++ % palette.length]
const slug = (value: string) => value.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-+|-+$/g, '')

function artist(name: string, tags: string[], query = name): CatalogEntry {
  return { id: `artist-${slug(name)}`, name, query, tags, tint: nextTint(), kind: 'artist' }
}
function mix(name: string, query: string, tags: string[]): CatalogEntry {
  return { id: `mix-${slug(name)}`, name, query, tags, tint: nextTint(), kind: 'mix' }
}

